/**
 * Acceptance fixtures A1–A5 (Google SDLC addendum): evidence-linked consumers, internal-only changes,
 * removed/renamed exports, dynamic loading and generated code, and degraded mode. Expectations live in ./expected
 * and were written before the analyzers.
 */
import { describe, expect, it } from "vitest";
import { Repo, cli } from "../helpers.js";
import { acceptanceRepo, FORMAT_TS, TAX_TS } from "./fixtures.js";
import { assertExpectation, loadExpectation } from "./harness.js";

type Json = Record<string, unknown>;
const head = ["--base", "main", "--head", "HEAD"];

async function report(repo: Repo, args = head): Promise<Json> {
  const r = await cli(["analyze", "--format", "json", "--quiet", ...args], repo.dir);
  expect(r.code, r.stderr).toBe(0);
  return JSON.parse(r.stdout) as Json;
}

function changed(files: Record<string, string>, remove: string[] = []): Repo {
  const repo = Repo.create(acceptanceRepo).branch("feature");
  repo.write(files);
  if (remove.length > 0) repo.remove(...remove);
  repo.commit("change");
  return repo;
}

describe("A1 — known reverse imports → evidence-linked affected consumers", () => {
  it("lists exactly the real consumers, each with the import line and commit", async () => {
    const repo = changed({ "src/utils/format.ts": FORMAT_TS.replace("toFixed(2)", "toFixed(3)") });
    assertExpectation(await report(repo), loadExpectation("a1-reverse-imports"));
  });
});

describe("A2 — internal-only change → no unsupported breaking-API claim", () => {
  it("does not report public API changes for body-only edits", async () => {
    const repo = changed({
      "src/utils/tax.ts": TAX_TS.replace("Math.round(n)", "Math.floor(n + 0.5)").replace(
        "cents * (1 + rate)",
        "cents + cents * rate"
      ),
    });
    assertExpectation(await report(repo), loadExpectation("a2-internal-change"));
  });
});

describe("A3 — deleted or renamed exports", () => {
  it("a: removed export still imported → verified static fact", async () => {
    const repo = changed({
      "src/utils/format.ts": FORMAT_TS.replace('\nexport const CURRENCY = "USD";\n', "\n"),
    });
    assertExpectation(await report(repo), loadExpectation("a3a-removed-export"));
  });
  it("b: renamed export → removal fact + possible rename + every importer", async () => {
    const repo = changed({ "src/utils/format.ts": FORMAT_TS.replace("formatPrice", "formatAmount") });
    assertExpectation(await report(repo), loadExpectation("a3b-renamed-export"));
  });
  it("c: module with export * → unknown, not a high-severity claim", async () => {
    const repo = changed({ "src/utils/index.ts": 'export * from "./format";\n' });
    assertExpectation(await report(repo), loadExpectation("a3c-star-reexport"));
  });
  it("d: signature change → hypothesis only", async () => {
    const repo = changed({
      "src/utils/format.ts": FORMAT_TS.replace("(cents: number)", '(cents: number, locale = "en")'),
    });
    assertExpectation(await report(repo), loadExpectation("a3d-signature-change"));
  });
});

describe("A4 — dynamic imports, reflection, generated code → limitations", () => {
  it("reports each construct as an explicit coverage limitation", async () => {
    const repo = changed({
      "src/plugins/loader.ts":
        acceptanceRepo["src/plugins/loader.ts"] +
        'export const ctx = (require as any).context("./plugins", true, /\\.ts$/);\nexport const pages = (import.meta as any).glob("./pages/*.ts");\nexport const v = eval("1 + 1");\n',
      "src/__generated__/schema.ts":
        "// @generated by schema-tool. DO NOT EDIT.\nexport const schema = {};\n",
      "src/api.pb.ts": "export const Api = {};\n",
      "src/models.gen.ts": "export const Models = {};\n",
    });
    const r = await report(repo);
    assertExpectation(r, loadExpectation("a4-dynamic-generated"));
    const generated = (r["changed_files"] as Json[])
      .filter((f) => f["generated"] === true)
      .map((f) => f["path"]);
    expect(generated.sort()).toEqual(["src/__generated__/schema.ts", "src/api.pb.ts", "src/models.gen.ts"]);
  });
});

describe("A5 — no relevant dependency graph → graceful degraded output", () => {
  it("reports observed changes only and says the graph is unavailable", async () => {
    const repo = Repo.create({
      "README.md": "# py\n",
      "app/main.py": "from app.util import f\nprint(f())\n",
      "app/util.py": "def f():\n    return 1\n",
    }).branch("f");
    repo.write({ "app/util.py": "def f():\n    return 2\n" });
    repo.commit("py change");
    const r = await report(repo);
    assertExpectation(r, loadExpectation("a5-degraded"));
    expect((r["changed_files"] as Json[]).map((f) => f["path"])).toEqual(["app/util.py"]);
    const md = await cli(["analyze", ...head, "--quiet"], repo.dir);
    expect(md.stdout).toContain("Degraded analysis");
  });
});
